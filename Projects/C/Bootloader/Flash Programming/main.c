void writePage(uint16_t page_start_address, uint16_t data){
	PORTB |= 0x20; //Turn on the LED.
	//***pgm_read_byte takes a byte address.
	
	uint16_t data_temp= 0;
	//uint8_t sreg;
	
	//sreg = SREG;
	
	cli();	//Disable interrupts.
	boot_page_erase(page_start_address);	//Erase the page to be written (word address).
	boot_spm_busy_wait();	//Wait till the erase is complete.
	
	for(uint8_t i = 0; i< PAGE_SIZE; i+= 2){		//Increment two addresses since data is written byte-wise even though addressing is done word-wise (??).	
		data_temp = (pgm_read_word_near(data + i));		//No need to convert to little endian. read_word requires a byte address.	
		boot_page_fill(page_start_address + i, data_temp); //Word address and a data word.
	}
	

	boot_page_write(page_start_address);	//Write data to the flash.
	boot_spm_busy_wait();		//Wait till the write is complete.
	
	
	
	boot_rww_enable();		//Re-enable reading the RWW section after programming the RWW section (required when executing code in the application section).
	sei();		//Re-enable interrupts.
	
	PORTB &= ~0x20; //For testing.
	
}

